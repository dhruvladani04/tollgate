def get(url: str) -> dict:
    return {"url": url, "max_length": 5000}


def send(method: str, url: str, body=None, headers=None) -> dict:
    request = {"method": method, "url": url}
    if headers:
        request["headers"] = headers
    if body is not None:
        request["body"] = body
    return request


